#!/bin/sh
# Контрольная сумма релизного ассета: сбор с зеркал и голосование. Вынесено из hysteria.sh, потому
# что это отдельная ответственность — единственное место, где решается «можно ли доверять байтам»,
# которые лягут в /usr/bin и будут исполняться от root. Сорсится hysteria.sh ПОСЛЕ fetch.sh; сам по
# себе не исполняется.
#
# Публичный контракт: collect_sha <asset> -> сумма на stdout.
#   rc 0 — сумма-победитель (пусто = не опубликована ни на одном зеркале)
#   rc 2 — зеркала расходятся: у лидера столько же голосов, сколько у другого варианта
#   rc 3 — подтверждений меньше MIN_VOTES
#   rc 4 — не удалось создать временный файл
# HASHES/SUM_TIMEOUT/mirrors()/mb_fetch приходят из hysteria.sh и fetch.sh.
# shellcheck shell=sh disable=SC2154

# Сумму с ОДНОГО зеркала брать нельзя: gh-прокси в списке — это MITM по устройству, и подменивший
# бинарь подменит на том же зеркале и строку в hashes.txt. Два независимых прокси требуют от
# атакующего оба сразу. Порог вынесен в переменную для случая, когда зеркала заданы через uci и их
# меньше двух: тогда установка честно отказывает, а не делает вид, что что-то проверила.
MIN_VOTES="${MB_HY_MIN_VOTES:-2}"

# Свой лимит времени на файл, не трогая MB_FETCH_TIMEOUT остальных вызовов: переменная читается
# mb_fetch в момент вызова и живёт до конца процесса.
fetch_timed() { # <секунды> <url> <out>
	_t="${MB_FETCH_TIMEOUT:-120}"
	MB_FETCH_TIMEOUT="$1"
	mb_fetch "$2" "$3"; _rc=$?
	MB_FETCH_TIMEOUT="$_t"
	return "$_rc"
}

# Строка файла сумм: "<sha256>  build/hysteria-linux-arm64". Имя якорим на конец, иначе
# hysteria-linux-arm подобрал бы сумму от hysteria-linux-arm64 — и бинарь не прошёл бы сверку с
# сообщением «сумма не сошлась», уводящим от настоящей причины.
sha_from_hashes() { # <file> <asset>
	awk -v a="$2" '$2 ~ ("(^|/)" a "$") { print $1; exit }' "$1"
}

# Голосование, а не «все обязаны совпасть»: URL зеркал указывают на latest/download, то есть не
# привязаны к релизу, и прокси с устаревшим кешем отдаёт сумму прошлой версии. Требование полного
# согласия отменяло бы установку из-за него, хотя большинство сошлось; бинарь при этом всё равно
# сверяется с суммой-победителем, так что зеркало со старым кешем просто не пройдёт сверку и
# перебор уйдёт к следующему.
collect_sha() { # <asset>
	f="$(mktemp "${TMPDIR:-/tmp}/mb-hyvote.XXXXXX")" || return 4
	for base in $(mirrors); do
		t="$(mktemp "${TMPDIR:-/tmp}/mb-hysum.XXXXXX")" || continue
		s=""
		if fetch_timed "$SUM_TIMEOUT" "$base/$HASHES" "$t" 2>/dev/null && [ -s "$t" ]; then
			s="$(sha_from_hashes "$t" "$1")"
		fi
		rm -f "$t"
		[ -n "$s" ] && echo "$s" >>"$f"
	done
	# "<голосов> <сумма>" по убыванию голосов
	tally="$(sort "$f" | uniq -c | sort -rn)"
	rm -f "$f"
	best="$(echo "$tally" | awk 'NR==1{print $2}')"
	[ -n "$best" ] || return 0
	best_n="$(echo "$tally" | awk 'NR==1{print $1}')"
	next_n="$(echo "$tally" | awk 'NR==2{print $1}')"
	[ "$best_n" -ge "$MIN_VOTES" ] || return 3
	[ -z "$next_n" ] || [ "$best_n" -gt "$next_n" ] || return 2
	echo "$best"
}
